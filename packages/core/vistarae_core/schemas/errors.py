"""Standard RFC 7807 / RFC 9457 Problem Details error schemas.

Enforces Constitution Principle 5 and Section 5.1 of specification.
"""

from __future__ import annotations

from pydantic import Field

from vistarae_core.schemas.base import StrictBaseModel


class InvalidParam(StrictBaseModel):
    """Granular error breakdown for schema validation failures."""

    name: str = Field(..., description="Field path or parameter name")
    reason: str = Field(..., description="Explanation of validation failure")


class ProblemDetails(StrictBaseModel):
    """RFC 7807 / RFC 9457 error representation envelope."""

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type",
    )
    title: str = Field(..., description="Short, human-readable summary of problem")
    status: int = Field(..., description="HTTP status code generated by server")
    detail: str = Field(..., description="Human-readable explanation specific to occurrence")
    instance: str | None = Field(
        default=None,
        description="URI reference identifying specific occurrence of problem",
    )
    invalid_params: list[InvalidParam] | None = Field(
        default=None,
        description="Detailed list of parameter or field validation errors",
    )
